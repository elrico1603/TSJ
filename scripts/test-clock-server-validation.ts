import assert from 'node:assert/strict';
import { validateAuthorizedClockEvent, sameClockEvent } from '../server/clocking/clockEventValidation';
const person='fictional-worker-001',device='fictional-device-001';
const identity={firebaseUid:'verified-fake-user',deviceId:device,permittedEmployeeIds:[person]};
const event={id:'7b0db063-99de-4a09-8f9a-11e79d782acb',employeeId:person,deviceId:device,action:'In',occurredAt:'2026-10-30T06:00:00.000Z'};
const now=new Date('2026-10-30T12:00:00.000Z');
assert.equal(validateAuthorizedClockEvent(event,identity,now).id,event.id);
console.log('PASS valid event');
assert.throws(()=>validateAuthorizedClockEvent(event,null,now));
console.log('PASS no verified device refused');
assert.throws(()=>validateAuthorizedClockEvent({...event,deviceId:'other-device-001'},identity,now));
console.log('PASS different device refused');
assert.throws(()=>validateAuthorizedClockEvent({...event,employeeId:'other-worker-001'},identity,now));
console.log('PASS unauthorized employee refused');
assert.equal(validateAuthorizedClockEvent({...event,occurredAt:'2026-10-09T06:00:00.000Z'},identity,now).action,'In');
console.log('PASS three week offline event retained');
assert.throws(()=>validateAuthorizedClockEvent({...event,occurredAt:'2026-08-01T06:00:00.000Z'},identity,now));
console.log('PASS very old event sent for review');
assert.throws(()=>validateAuthorizedClockEvent({...event,occurredAt:'2026-10-30T12:06:00.000Z'},identity,now));
console.log('PASS future time sent for review');
const receipt={eventId:event.id,employeeId:person,deviceId:device,action:'In',occurredAt:event.occurredAt};
assert.equal(sameClockEvent(receipt,event as any),true);
assert.equal(sameClockEvent({...receipt,action:'Out'},event as any),false);
console.log('PASS duplicate ID must match immutable fields');
console.log('All 8 clock server validation checks passed.');
