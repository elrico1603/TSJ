import { readdirSync, readFileSync, writeFileSync, existsSync } from 'node:fs';
import { resolve } from 'node:path';

const folder=resolve('src/module-manifests');
const output=resolve('src/generated/modulePermissionCatalog.ts');
const files=existsSync(folder)?readdirSync(folder).filter(file=>file.endsWith('.module.json')).sort():[];
const groups=new Map();
const ids=new Set(),names=new Set();
for(const file of files){
  const manifest=JSON.parse(readFileSync(resolve(folder,file),'utf8'));
  const {id,name,category,permissions}=manifest;
  if(typeof id!=='string'||!/^[a-z][a-z0-9_-]*$/.test(id)||ids.has(id))throw Error('Invalid or duplicate module ID: '+id);
  if(typeof name!=='string'||!name.trim()||typeof category!=='string'||!category.trim())throw Error('Invalid module metadata: '+file);
  if(!Array.isArray(permissions)||!permissions.length)throw Error('Module has no permission definitions: '+file);
  ids.add(id);
  for(const item of permissions){
    if(typeof item!=='string'||!item.trim()||item.length>100||names.has(item))
      throw Error('Invalid or duplicated permission name: '+item);
    names.add(item);
    if(!groups.has(category))groups.set(category,[]);
    groups.get(category).push(item);
  }
}
const list=[...groups.entries()].map(([category,modules])=>({category,modules}));
const namesList=[...names];
const source='// Generated by scripts/sync-module-permissions.mjs. Do not edit by hand.\n'+
  'export const GENERATED_PERMISSION_MODULE_GROUPS: {category:string;modules:string[]}[] = '+JSON.stringify(list,null,2)+';\n'+
  'export const GENERATED_PERMISSION_MODULE_NAMES: string[] = '+JSON.stringify(namesList,null,2)+';\n';
if(process.argv.includes('--check')){
  if(!existsSync(output)||readFileSync(output,'utf8')!==source)throw Error('Module permission catalog is out of sync. Run npm run permissions:sync');
  console.log('Module permission catalog synchronized: '+namesList.length+' feature permissions.');
}else{
  writeFileSync(output,source);
  console.log('Generated '+namesList.length+' feature permissions from '+files.length+' module manifests.');
}
